"""Renders the committed reports from a replay's results and its warehouse. Numbers in the
README come from these files; nothing here is typed by hand."""
from __future__ import annotations

import json
from pathlib import Path

import duckdb

from acm.recon import STEPS


def _usd(v: float) -> str:
    return f"${v:,.2f}"


def evaluation(rep: dict) -> str:
    w, ev = rep["world"], rep["evaluation"]
    sep, oct_ = ev["2026-09"], ev["2026-10"]
    nv = ev.get("naive", {})
    lines = [
        "# Evaluation", "",
        f"Generated by `acm replay` (seed {w['seed']}, all faults on). The simulator builds a GPU cloud with "
        f"{w['customers']} customers, {w['vms']} VMs and {w['commitments']} reserved-capacity commitments, and delivers "
        f"{w['events_ingested']:,} events in {w['landing_files']:,} landing files with every fault in "
        "`src/acm/sim/delivery.py`. The pipeline runs every "
        f"{w['step_hours']} h on a simulated clock from 1 September to 18 October ({w['pipeline_runs']} runs), "
        "closes September on 3 October at 12:00 and keeps going. The truth is computed from the simulator's own "
        "world, which the pipeline never reads (tests/test_isolation.py).", "",
        "## Revenue against the truth", "",
        "| | September (closed) | October (open, to 16 Oct) |", "|---|---|---|",
        f"| Truth | {_usd(sep['truth'])} | {_usd(oct_['truth'])} |",
        f"| This platform | {_usd(sep['ours'])} | {_usd(oct_['ours'])} |",
        f"| Largest customer-month error | {_usd(sep['max_customer_error'])} | {_usd(oct_['max_customer_error'])} |",
        f"| ... for customers with no lost stop event | {_usd(sep['max_error_without_inferred_stop'])} | "
        f"{_usd(oct_['max_error_without_inferred_stop'])} |",
        f"| Customers with a lost stop event | {sep['customers_with_inferred_stop']} | {oct_['customers_with_inferred_stop']} |",
        f"| Reported at close (3 Oct 12:00) | {_usd(sep.get('closed_total', 0))} | - |",
        f"| Adjustments after close | {_usd(sep.get('adjustments', 0))} | - |",
    ]
    if nv:
        lines += [
            f"| Naive pipeline | {_usd(nv['2026-09']['naive'])} ({nv['2026-09']['naive'] - nv['2026-09']['truth']:+,.2f}) | "
            f"{_usd(nv['2026-10']['naive'])} ({nv['2026-10']['naive'] - nv['2026-10']['truth']:+,.2f}) |",
        ]
    lines += [
        "",
        "A lost stop event cannot be recovered exactly: the session is billed to one heartbeat after its last "
        "heartbeat (docs/BILLING_RULES.md), the truth knows when it really stopped. That is the only source of "
        "error above a cent. The naive pipeline is `src/acm/naive.py`: processing-time months, no de-duplication, "
        "heartbeat counting, every commitment row charged.", "",
        "## What happened, run by run", "",
        "| run at (UTC) | files | rows | closed | restated | alerts opened |", "|---|---|---|---|---|---|",
    ]
    for t in rep["timeline"]:
        if t["closed"] or t["restated_usd"] or t["alerts_opened"]:
            lines.append(f"| {t['at'][:16].replace('T', ' ')} | {t['files']} | {t['rows']:,} | {', '.join(t['closed'])} | "
                         f"{_usd(t['restated_usd']) if t['restated_usd'] else ''} | {', '.join(t['alerts_opened'])} |")
    lines += ["", "## Alerts", "", "| check | key | opened | resolved | message |", "|---|---|---|---|---|"]
    for a in rep["alerts"]:
        note = " (simulated producers stopped)" if a.get("after_simulation_end") else ""
        lines.append(f"| {a['check']} | {a['key']} | {a['opened_at'][:16].replace('T', ' ')} | "
                     f"{(a['resolved_at'] or 'open')[:16].replace('T', ' ')} | {a['message']}{note} |")
    secs = [t["seconds"] for t in rep["timeline"]]
    lines += ["", "## Cost of a run", "",
              f"A pipeline run took {sum(secs) / len(secs):.1f} s on average and {max(secs):.1f} s at most "
              f"(the whole replay: {rep['seconds']:.0f} s, including the simulator and the naive pipeline). Bronze "
              f"ended with {w['bronze_files_after_compaction']} Parquet files after compaction.", ""]
    return "\n".join(lines)


def reconciliation(con: duckdb.DuckDBPyConnection, month: str = "2026-09") -> str:
    rows = con.execute("SELECT * FROM recon_waterfall WHERE month = ? ORDER BY customer_id", [month]).fetchall()
    cols = [d[0] for d in con.execute("DESCRIBE recon_waterfall").fetchall()]
    rs = [dict(zip(cols, r)) for r in rows]
    tot = {k: round(sum(r[k] for r in rs), 2) for k in ["ours", "invoiced", *STEPS, "unexplained"]}
    rs = [r for r in rs if "credits_difference" in r] or rs
    worst = max((abs(r["unexplained"]) for r in rs), default=0.0)
    lines = [
        "# Reconciliation", "",
        f"Generated by `acm replay`. The billing system invoiced {month} on 3 October at 12:00 with what it had, "
        "and with five behaviours of its own. The platform reconciles every invoice against its own number and "
        "explains the difference in charges before prepaid credits as a waterfall (`src/acm/recon.py`): each step "
        "re-runs the platform's own models "
        "with one of the billing system's behaviours switched on, so a step that is wrong explains nothing and "
        "the difference stays unexplained.", "",
        "| step | what it is | amount |", "|---|---|---|",
        f"| ours | this platform's charges after restatements, before credits | {_usd(tot['ours'])} |",
        f"| late_usage | what billing could not have seen at its cutoff | {_usd(tot['late_usage'])} |",
        f"| missing_stop_event | sessions without a stop event billed to month end | {_usd(tot['missing_stop_event'])} |",
        f"| hourly_rounding | us-central1 sessions rounded up to whole hours | {_usd(tot['hourly_rounding'])} |",
        f"| overlapping_commitment | renewals charged on top of the commitment they replace | "
        f"{_usd(tot['overlapping_commitment'])} |",
        f"| duplicate_events | inference retries counted twice | {_usd(tot['duplicate_events'])} |",
        f"| unexplained | | {_usd(tot['unexplained'])} |",
        f"| **invoiced** | charges before credits | **{_usd(tot['invoiced'])}** |", "",
        f"Largest unexplained difference for a single customer: {_usd(worst)} (the check fails above $1.00).", "",
        "## By customer", "",
        "| customer | ours | invoiced | late | stop | rounding | commitment | duplicates | unexplained |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in sorted(rs, key=lambda r: -abs(r["invoiced"] - r["ours"])):
        if abs(r["invoiced"] - r["ours"]) < 0.005:
            continue
        lines.append(f"| {r['customer_id']} | {_usd(r['ours'])} | {_usd(r['invoiced'])} | " +
                     " | ".join(f"{r[s]:+,.2f}" for s in STEPS) + f" | {r['unexplained']:+,.2f} |")
    hidden = [r for r in rs if abs(r.get("credits_difference", 0.0)) >= 1.0]
    lines += ["", "## Prepaid credits", "",
              f"The billing system consumed {_usd(sum(r['credits_difference'] for r in rs))} more of customers' prepaid "
              "credits than the platform did. On these customers the invoice total agrees (credits paid the "
              "overcharge) and only the remaining balance shows it; the waterfall above attributes the charge:", ""]
    if hidden:
        lines += ["| customer | credits used by billing minus ours | of which explained above |", "|---|---|---|"]
        lines += [f"| {r['customer_id']} | {r['credits_difference']:+,.2f} | "
                  f"{sum(r[s] for s in STEPS):+,.2f} |" for r in sorted(hidden, key=lambda r: -abs(r["credits_difference"]))]
    else:
        lines.append("None.")
    return "\n".join(lines) + "\n"


def write_all(rep_path: Path, warehouse: Path, out: Path) -> list[Path]:
    rep = json.loads(rep_path.read_text())
    out.mkdir(parents=True, exist_ok=True)
    written = [out / "EVALUATION.md", out / "RECONCILIATION.md"]
    written[0].write_text(evaluation(rep))
    con = duckdb.connect(str(warehouse), read_only=True)
    try:
        written[1].write_text(reconciliation(con))
    finally:
        con.close()
    return written
